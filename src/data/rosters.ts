const createStudent = (stt: number, sbdPrefix: string, fullName: string): Student => {
  const sttStr = stt.toString().padStart(2, '0');
  const sbd = `${sbdPrefix}${sttStr}`;
  return {
    stt,
    sttStr,
    sbd,
    fullName,
  };
};


// Generate sample roster for other classes
const generateClassStudents = (classId: string, count = 40): Student[] => {
  const grade = classId.substring(0, 2);
  const section = classId.substring(2);
  const sbdPrefix = `${grade}${section === 'A1' ? '1' : section === 'A2' ? '2' : section === 'A3' ? '3' : section === 'A4' ? '4' : section === 'A5' ? '5' : section === 'A6' ? '6' : '7'}0`;
  const names = [
    'Nguyễn Văn An', 'Trần Thị Bình', 'Lê Hoàng Cường', 'Phạm Minh Đức', 'Võ Thảo Giang',
    'Đặng Quốc Huy', 'Bùi Mỹ Linh', 'Hồ Tấn Nam', 'Dương Yến Nhi', 'Lý Gia Phúc',
    'Huỳnh Ngọc Sang', 'Ngô Quốc Thịnh', 'Phan Thanh Tú', 'Trương Tuấn Vũ', 'Đỗ Mai Anh',
    'Vũ Hồng Bảo', 'Đoàn Bảo Châu', 'Chu Hải Đăng', 'Lâm Phương Hà', 'Mai Khánh Hưng',
    'Trịnh Nhật Khang', 'Lương Kiều My', 'Cao Tuấn Kiệt', 'Tạ Minh Long', 'Nguyễn Tấn Tài',
    'Bùi Đình Trọng', 'Phan Thùy Trang', 'Lê Gia Uy', 'Hà Thảo Vy', 'Trương Gia Ân',
    'Đinh Khắc Duy', 'Nguyễn Bảo Hân', 'Đào Quang Huy', 'Vương Ngọc Lan', 'Hồ Diệu Linh',
    'Phạm Trí Minh', 'Lưu Hồng Nga', 'Trần Đại Nghĩa', 'Vũ Tuyết Nhung', 'Nguyễn Anh Phát'
  ];

  return Array.from({ length: count }, (_, i) => {
    const stt = i + 1;
    const name = names[i % names.length] + (i >= names.length ? ` (${stt})` : '');
    return createStudent(stt, sbdPrefix, name);
  });
};

